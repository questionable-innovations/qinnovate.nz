// Pack raw calligrapher.ai captures (see generate-handwriting.mjs) into small
// per-title JSON files the page picks from at random.
//   node scripts/pack-handwriting.mjs <raw-dir> [--keep id,id,...]
// Output: static/hand/<n>.json + src/lib/hand-count.ts
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';

const [dir, flag, list] = process.argv.slice(2);
const keep = flag === '--keep' ? new Set(list.split(',')) : null;
const Q = 2; // quantise to half-pixel units

/** calligrapher paths are `M x,y C x y, x y, x y ...`: re-emit relative, integer, compact */
function pack(d, ox, oy) {
	const out = [];
	let cx = 0, cy = 0;
	const q = (v, o) => Math.round((v - o) * Q);
	const num = (arr) => arr.map((v, i) => (i && v >= 0 ? ' ' : '') + v).join('');
	for (const [, cmd, body] of d.matchAll(/([MC])([^MC]*)/g)) {
		const n = body.trim().split(/[\s,]+/).filter(Boolean).map(Number);
		if (cmd === 'M') {
			cx = q(n[0], ox);
			cy = q(n[1], oy);
			out.push('M' + num([cx, cy]));
		} else {
			for (let i = 0; i + 5 < n.length; i += 6) {
				const pts = [0, 2, 4].map((k) => [q(n[i + k], ox), q(n[i + k + 1], oy)]);
				const seg = num(pts.flatMap(([x, y]) => [x - cx, y - cy]));
				// repeated curves need no command letter, just a separator before a positive number
				const first = !out.length || out[out.length - 1].startsWith('M');
				out.push(first ? 'c' + seg : (seg[0] === '-' ? '' : ' ') + seg);
				[cx, cy] = pts[2];
			}
		}
	}
	return out.join('');
}

const word = (w) => {
	const [x, y, bw, bh] = w.vb;
	return { w: Math.ceil(bw * Q), h: Math.ceil(bh * Q), d: w.paths.map((d) => pack(d, x, y)) };
};

const ids = readdirSync(dir).filter((f) => f.endsWith('.json')).map((f) => f.slice(0, -5)).sort();
const chosen = keep ? ids.filter((id) => keep.has(id)) : ids;
rmSync('static/hand', { recursive: true, force: true });
mkdirSync('static/hand', { recursive: true });
let bytes = 0;
chosen.forEach((id, n) => {
	const raw = JSON.parse(readFileSync(`${dir}/${id}.json`, 'utf8'));
	const json = JSON.stringify({ q: word(raw.Questionable), i: word(raw.Innovations) });
	writeFileSync(`static/hand/${n}.json`, json);
	bytes += json.length;
});
writeFileSync(
	'src/lib/hand-count.ts',
	`// generated by scripts/pack-handwriting.mjs\nexport const HAND_COUNT = ${chosen.length};\n`
);
console.log(`${chosen.length} titles, avg ${(bytes / chosen.length / 1024).toFixed(1)} KB`);
